#!/usr/bin/env python3
"""Slice the ownership guard out of the vendor's AddContactView.swift and wrap
it into a callable, WITHOUT editing a single byte of the vendor source.

The emitted Swift file contains the guard block verbatim. Downstream assertions
therefore execute the vendor's own condition, not a reimplementation of it.

The verbatim block ends in a bare `return`, which would be illegal inside a
function that returns a value. It is therefore nested inside a `Void` function,
where a bare `return` simply exits that inner scope. A flag captured from the
outer scope records whether the guard fired, so the wrapper can report the
outcome without touching the copied text.
"""

import hashlib
import pathlib
import sys

HARNESS_DIR = pathlib.Path(__file__).resolve().parents[1]   # .../retest/harness

# Vendor source: explicit argv[1] wins, then the usual clone locations.
CANDIDATES = [
    *([pathlib.Path(sys.argv[1])] if len(sys.argv) > 1 else []),
    pathlib.Path("vendor/privamesh/Views/Chat/AddContactView.swift"),
    HARNESS_DIR.parents[0] / "vendor/privamesh/Views/Chat/AddContactView.swift",
    pathlib.Path("/root/audit/privamesh/privamesh/Views/Chat/AddContactView.swift"),
]
OUT = HARNESS_DIR / "Sources/PMInterop/GuardSlice.swift"

START, END = 601, 605  # the `if bundle.walletAddress != nil, !bundle.isBoundTo(...)` block


def locate() -> pathlib.Path:
    for p in CANDIDATES:
        if p.is_dir():
            p = p / "privamesh/Views/Chat/AddContactView.swift"
        if p.exists():
            return p
    print("ERROR: AddContactView.swift not found. Run from the repo root after "
          "cloning the vendor source into vendor/.", file=sys.stderr)
    raise SystemExit(1)


def main() -> int:
    vendor = locate()
    src = vendor.read_text(encoding="utf-8").splitlines(keepends=True)
    block = "".join(src[START - 1:END])
    digest = hashlib.sha256(block.encode()).hexdigest()

    if "walletAddress != nil" not in block:
        print(f"ERROR: lines {START}-{END} do not contain the guard. Vendor source "
              f"may have moved; re-check line numbers.", file=sys.stderr)
        return 1
    if "isBoundTo" not in block:
        print(f"ERROR: lines {START}-{END} contain no isBoundTo() call.", file=sys.stderr)
        return 1

    header = f"""//
//  GuardSlice.swift — GENERATED by harness/scripts/slice_guard.py. Do not edit.
//
//  Verbatim copy of privamesh/Views/Chat/AddContactView.swift lines {START}-{END}
//  from github.com/Makomest/PrivaMesh @ afb5ef9.
//
//  sha256 of the copied block: {digest}
//
//  The block is nested in a Void function so its bare `return` stays legal and
//  the copied text needs no modification.
//

import Foundation

/// Mirrors only the one property the vendor block reads off `card`.
struct CardRef {{ let address: String }}

func realAddFromQRGuard(bundle: PrekeyBundle, cardAddress: String) -> (accepted: Bool, reason: String) {{
    var errorMessage: String?
    var showError = false
    let card = CardRef(address: cardAddress)
    var guardFired = true

    func inner() {{
"""

    footer = """
        guardFired = false
    }

    _ = showError   // written by the vendor block, read here only to keep the log clean

    inner()

    if guardFired {
        return (false, "REJECTED: walletAddress present and isBoundTo() == false"
                     + (errorMessage.map { " (\\($0))" } ?? ""))
    }
    return (true, "ACCEPTED: guard did not fire")
}
"""

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(header + block + footer, encoding="utf-8")

    print(f"vendor source      : {vendor}")
    print(f"guard block sha256 : {digest}")
    print(f"guard block bytes  : {len(block.encode())}")
    print(f"wrote              : {OUT}")
    for i, line in enumerate(block.splitlines(), start=START):
        print(f"  {i}| {line}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

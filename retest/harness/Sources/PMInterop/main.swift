var failures = 0

func check(_ label: String, _ ok: Bool, _ detail: String = "") {
    let mark = ok ? "PASS" : "FAIL"
    print("[\(mark)] \(label)\(detail.isEmpty ? "" : "  — \(detail)")")
    if !ok { failures += 1 }
}

func section(_ title: String) { print("\n=== \(title) ===") }

func hex(_ d: Data) -> String { d.map { String(format: "%02x", $0) }.joined() }

func b64url(_ d: Data) -> String {
    d.base64EncodedString()
        .replacingOccurrences(of: "+", with: "-")
        .replacingOccurrences(of: "/", with: "_")
        .replacingOccurrences(of: "=", with: "")
}

// MARK: - Identities

/// A messaging identity: the three keys a PrekeyBundle publishes, plus the
/// optional wallet binding material.
struct MeshIdentity {
    let dhIK: Curve25519.KeyAgreement.PrivateKey
    let sigIK: Curve25519.Signing.PrivateKey
    let spk: Curve25519.KeyAgreement.PrivateKey

    init() {
        dhIK = Curve25519.KeyAgreement.PrivateKey()
        sigIK = Curve25519.Signing.PrivateKey()
        spk = Curve25519.KeyAgreement.PrivateKey()
    }

    /// Unsigned bundle: no walletAddress, no walletSignature.
    /// This is a legitimate shape — the repo's own golden vector
    /// (privameshTests/vectors/kotlin_contact_card.json) omits both fields.
    func unsignedBundle() throws -> PrekeyBundle {
        let sig = try sigIK.signature(for: spk.publicKey.rawRepresentation)
        return PrekeyBundle(
            dhIdentityKey: dhIK.publicKey.rawRepresentation,
            signedPrekeyPublic: spk.publicKey.rawRepresentation,
            signedPrekeySignature: Data(sig),
            oneTimePrekeyPublic: nil,
            signingIdentityKey: sigIK.publicKey.rawRepresentation
        )
    }

    /// Unsigned bundle that additionally *claims* an address it cannot prove.
    func bundleClaiming(address: String) throws -> PrekeyBundle {
        var b = try unsignedBundle()
        b.walletAddress = address
        return b
    }
}

/// A bundle genuinely bound to a wallet — the shape a real device publishes.
func walletBoundBundle(wallet: Curve25519.Signing.PrivateKey) throws -> PrekeyBundle {
    let dh = Curve25519.KeyAgreement.PrivateKey()
    let sig = Curve25519.Signing.PrivateKey()
    let spk = Curve25519.KeyAgreement.PrivateKey()
    let spkSig = try sig.signature(for: spk.publicKey.rawRepresentation)
    let raw = try PrekeyBundle(
        dhIdentityKey: dh.publicKey.rawRepresentation,
        signedPrekeyPublic: spk.publicKey.rawRepresentation,
        signedPrekeySignature: Data(spkSig),
        oneTimePrekeyPublic: nil,
        signingIdentityKey: sig.publicKey.rawRepresentation
    )
    var secret = wallet.rawRepresentation                    // 32-byte Ed25519 seed
    secret.append(wallet.publicKey.rawRepresentation)        // 32-byte public key
    let address = SolanaAddress.string(from: wallet.publicKey.rawRepresentation)
    return raw.walletSigned(address: address, keypair: KeyPair(secretKey: secret))
}

// MARK: - Part A — decode links produced outside the app (cross-implementation)
//
// Each link is generated by e2e/scripts/gen_attack_link.py (Python) and decoded
// here by the app's own Foundation/NSData path. That proves the payload format is
// not an artifact of one language's encoder.

let env = ProcessInfo.processInfo.environment

func inspectExternalLink(_ label: String, _ linkString: String, expectAccepted: Bool) {
    print("")
    print("— link: \(label) (\(linkString.count) chars)")
    guard let url = URL(string: linkString) else {
        check("\(label): link is a valid URL", false); return
    }
    guard let rawPayload = InviteLink.payload(from: url) else {
        check("\(label): InviteLink.payload(from:) extracts a payload", false); return
    }
    check("\(label): InviteLink.payload(from:) extracts a payload", true, "\(rawPayload.count) chars")

    let standard = InviteLink.base64Standard(rawPayload)
    guard let card = ContactCard.fromQRPayload(standard) else {
        check("\(label): ContactCard.fromQRPayload() decodes via NSData inflate", false); return
    }
    check("\(label): ContactCard.fromQRPayload() decodes via NSData inflate", true)

    check("\(label): card.hasValidAddress", card.hasValidAddress, card.address)
    check("\(label): card carries a nickname for prefill", card.profile?.nickname != nil,
          "nickname = \(card.profile?.nickname ?? "nil")")

    guard let bundle = try? PrekeyBundle.fromBase64(card.bundle) else {
        check("\(label): PrekeyBundle.fromBase64", false); return
    }
    let verdict = realAddFromQRGuard(bundle: bundle, cardAddress: card.address)
    check("\(label): vendor guard \(expectAccepted ? "ACCEPTS" : "REJECTS") the card",
          verdict.accepted == expectAccepted, verdict.reason)
}

section("PART A — decode externally generated invite links")

let externalLinks: [(String, String, Bool)] = [
    ("attack", env["PM_LINK_ATTACK"] ?? "", true),
    ("legit",  env["PM_LINK_LEGIT"]  ?? "", true),
    ("forged", env["PM_LINK_FORGED"] ?? "", false),
]

var testedExternal = 0
for (label, link, expectAccepted) in externalLinks where !link.isEmpty {
    inspectExternalLink(label, link, expectAccepted: expectAccepted)
    testedExternal += 1
}
if testedExternal == 0 {
    print("(no PM_LINK_* environment variables — skipping Part A)")
} else {
    check("all three link classes were exercised", testedExternal == 3, "\(testedExternal)/3")
}

// MARK: - Part B — three separate identities

section("PART B — impersonation with distinct wallets, real ratchet")

// Three identities, deliberately disjoint:
//   user         — opens the link and sends the traffic (their own wallet)
//   impersonated — the contact the card claims to be (never runs anything)
//   attacker     — owns the messaging keys in the card
let userWallet     = Curve25519.Signing.PrivateKey()
let userIdentity   = Curve25519.KeyAgreement.PrivateKey()
let userEphemeral  = Curve25519.KeyAgreement.PrivateKey()
let userAddress    = SolanaAddress.string(from: userWallet.publicKey.rawRepresentation)

let impersonatedWallet = Curve25519.Signing.PrivateKey()
let impersonatedAddress = SolanaAddress.string(from: impersonatedWallet.publicKey.rawRepresentation)

let attacker = MeshIdentity()

print("user's own address       : \(userAddress)")
print("impersonated address     : \(impersonatedAddress)")
check("the two wallets are distinct", userAddress != impersonatedAddress)
check("neither address is the attacker's wallet",
      SolanaAddress.string(from: attacker.sigIK.publicKey.rawRepresentation) != userAddress
      && SolanaAddress.string(from: attacker.sigIK.publicKey.rawRepresentation) != impersonatedAddress)

// --- the card the attacker sends
let publishedBundle = try attacker.unsignedBundle()
var card = ContactCard(address: impersonatedAddress, bundle: publishedBundle.base64Encoded)
card.profile = ProfileSnapshot(nickname: "Alice")

let link = InviteLink.url(for: card)!
print("attack link: \(link.absoluteString.prefix(64))…  (\(link.absoluteString.count) chars)")

// --- user side: the app receives the link, same call the deep link makes
guard let linkURL = URL(string: link.absoluteString),
      let raw = InviteLink.payload(from: linkURL) else {
    print("[FAIL] payload extraction failed"); exit(2)
}
guard let receivedCard = ContactCard.fromQRPayload(InviteLink.base64Standard(raw)) else {
    print("[FAIL] card decode failed"); exit(2)
}
check("user decodes the card", true, receivedCard.address)
check("card shows the impersonated address, not the attacker's", receivedCard.address == impersonatedAddress)
check("card prefills the display name the attacker chose", receivedCard.profile?.nickname == "Alice")

guard let receivedBundle = try? PrekeyBundle.fromBase64(receivedCard.bundle) else {
    print("[FAIL] bundle decode failed"); exit(2)
}

var verifyPassed = true
do { try receivedBundle.verify() } catch { verifyPassed = false }
check("PrekeyBundle.verify() passes (attacker signed its own SPK)", verifyPassed)

// --- the guard, compiled from the vendor's own source text
let verdict = realAddFromQRGuard(bundle: receivedBundle, cardAddress: receivedCard.address)
check("vendor guard ACCEPTS the attacker bundle", verdict.accepted, verdict.reason)

// --- controls: the guard works, it is bypassed
let legitBundle = try walletBoundBundle(wallet: impersonatedWallet)
check("control: a wallet-bound bundle passes isBoundTo",
      legitBundle.isBoundTo(address: impersonatedAddress))

let claimed = try attacker.bundleClaiming(address: impersonatedAddress)
check("control: an unsigned bundle that CLAIMS the address is not bound",
      !claimed.isBoundTo(address: impersonatedAddress))
let claimedVerdict = realAddFromQRGuard(bundle: claimed, cardAddress: impersonatedAddress)
check("control: claiming the address trips the guard", !claimedVerdict.accepted, claimedVerdict.reason)

// --- the exact tuple AddContactView.addFromQR hands to SwiftData (lines 606-616)
check("contact id the app will store == impersonated address", receivedCard.address == impersonatedAddress)
check("contact name the app will store == attacker-chosen name",
      (receivedCard.profile?.nickname ?? "") == "Alice")
// The stored bundle must carry the attacker's exact key material. JSON byte
// equality is not the point (re-encoding a decoded struct is not guaranteed to
// be byte-stable), so compare the keys the session is actually built from.
let sameKeyMaterial =
    receivedBundle.dhIdentityKey == publishedBundle.dhIdentityKey
    && receivedBundle.signingIdentityKey == publishedBundle.signingIdentityKey
    && receivedBundle.signedPrekeyPublic == publishedBundle.signedPrekeyPublic
    && receivedBundle.signedPrekeySignature == publishedBundle.signedPrekeySignature
check("contact bundle the app will store == attacker's published bundle",
      sameKeyMaterial,
      receivedBundle.base64Encoded == publishedBundle.base64Encoded
        ? "base64-identical"
        : "key material identical (base64 re-encoding differs)")

// --- user sends: X3DH over the stored bundle, exactly as MessageSender does
let userSK = try X3DH.senderSharedSecret(
    myIdentityKey: userIdentity,
    myEphemeralKey: userEphemeral,
    remoteBundle: receivedBundle)

let attackerSK = try X3DH.receiverSharedSecret(
    myIdentityKey: attacker.dhIK,
    mySignedPrekey: attacker.spk,
    senderIdentityKeyPublic: userIdentity.publicKey.rawRepresentation,
    senderEphemeralKeyPublic: userEphemeral.publicKey.rawRepresentation)

check("X3DH shared secrets match", userSK == attackerSK, "SK = \(hex(userSK).prefix(16))…")

// --- user encrypts through the real pipeline: pad -> ratchet -> envelope -> base64
let plaintext = Data("meet me at 9, bring the seed phrase backup".utf8)
let padded = MessagePadding.pad(plaintext)

var senderRatchet = try DoubleRatchet.initSender(
    sharedSecret: userSK,
    remoteSPKPublic: receivedBundle.signedPrekeyPublic)
let encrypted = try senderRatchet.encrypt(plaintext: padded)

let envelope = MessageEnvelope(
    kind: .sessionInit,
    senderIdentityPublic: userIdentity.publicKey.rawRepresentation,
    senderEphemeralPublic: userEphemeral.publicKey.rawRepresentation,
    message: encrypted)
let wireBase64 = envelope.base64
print("on-chain memo payload    : \(wireBase64.count) base64 chars")

// --- attacker side: parse the envelope the way PollingService does
let parsedEnvelope = try MessageEnvelope.fromBase64(wireBase64)
check("attacker parses the real MessageEnvelope", parsedEnvelope.kind == .sessionInit)

guard let senderIK = parsedEnvelope.senderIdentityPublic,
      let senderEK = parsedEnvelope.senderEphemeralPublic else {
    print("[FAIL] envelope is missing the session-init public keys"); exit(2)
}

let receiverSK = try X3DH.receiverSharedSecret(
    myIdentityKey: attacker.dhIK,
    mySignedPrekey: attacker.spk,
    senderIdentityKeyPublic: senderIK,
    senderEphemeralKeyPublic: senderEK)
check("attacker re-derives SK from the envelope alone", receiverSK == userSK)

var receiverRatchet = DoubleRatchet.initReceiver(sharedSecret: receiverSK, localSPK: attacker.spk)
let decryptedPadded = try receiverRatchet.decrypt(message: parsedEnvelope.message)
let recovered = try MessagePadding.unpad(decryptedPadded)

check("attacker decrypts the real Double Ratchet message", recovered == plaintext,
      "\"\(String(decoding: recovered, as: UTF8.self))\"")

// Second message on the advanced chain — both sides must stay in sync.
let secondPlaintext = Data("send the backup to this address instead".utf8)
let secondEnvelope = MessageEnvelope(
    kind: .regular,
    senderIdentityPublic: nil,
    senderEphemeralPublic: nil,
    message: try senderRatchet.encrypt(plaintext: MessagePadding.pad(secondPlaintext)))
let secondDecrypted = try MessagePadding.unpad(
    try receiverRatchet.decrypt(message: try MessageEnvelope.fromBase64(secondEnvelope.base64).message))
check("attacker decrypts the second message on the advanced chain",
      secondDecrypted == secondPlaintext,
      "\"\(String(decoding: secondDecrypted, as: UTF8.self))\"")

// --- the attacker cannot sign as either wallet
let probe = Data("anything".utf8)
let attackerSig = try attacker.sigIK.signature(for: probe)
let forgedAsVictim = (try? NaclSign.signDetachedVerify(
    message: probe, sig: Data(attackerSig),
    publicKey: impersonatedWallet.publicKey.rawRepresentation)) ?? false
check("attacker cannot forge a signature for the impersonated wallet", !forgedAsVictim)
let forgedAsUser = (try? NaclSign.signDetachedVerify(
    message: probe, sig: Data(attackerSig),
    publicKey: userWallet.publicKey.rawRepresentation)) ?? false
check("attacker cannot forge a signature for the user's wallet", !forgedAsUser)

section("SUMMARY")
print("failures: \(failures)")
print("user address              : \(userAddress)")
print("impersonated address      : \(impersonatedAddress)")
print("attacker dh identity      : \(hex(attacker.dhIK.publicKey.rawRepresentation))")
print("attacker signed prekey    : \(hex(attacker.spk.publicKey.rawRepresentation))")
print("attacker signing identity : \(hex(attacker.sigIK.publicKey.rawRepresentation))")
exit(failures == 0 ? 0 : 1)
